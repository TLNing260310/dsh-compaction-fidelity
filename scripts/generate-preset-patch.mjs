import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const APP_NODE_MODULES = process.env.DSH_APP_NODE_MODULES ?? 'D:/DSH/DSH Desktop/resources/app/node_modules';
const DSH_VERSION = process.env.DSH_VERSION ?? '0.2.0-rc.2';
const PRESETS = [
  { id: 'preset-standard', file: '@deepseek-ai/dsh-web-app/presets/standard.patch.yml' },
  { id: 'preset-cordis', file: '@deepseek-ai/dsh-web-app/presets/cordis.patch.yml' },
  { id: 'preset-ptc', file: '@deepseek-ai/dsh-web-app/presets/ptc.patch.yml' },
  { id: 'preset-minimal', file: '@deepseek-ai/dsh-web-app/presets/minimal.patch.yml' },
];

const ENGINE_ROW = {
  name: 'dsh-compaction-fidelity/engine',
  config: [
    ['enabled', 'true'],
    ['threshold', "'350k'"],
    ['retainTokens', '65536'],
    ['summaryLanguage', 'auto'],
    ['summaryMaxTokens', '65536'],
    ['compensationMaxTokens', '2048'],
    ['injectionMaxTokens', '16000'],
    ['compactionRetries', '1'],
    ['headroomTokens', '65536'],
    ['ledger', 'true'],
    ['anchors', 'true'],
    ['anchorsPerFile', '8'],
    ['indexDir', '.dsh/compaction-fidelity'],
  ],
};

function extractEntry(text, id) {
  const lines = text.split(/\r?\n/);
  const startPattern = new RegExp(`^    - id: ${id}\\s*$`);
  const start = lines.findIndex((line) => startPattern.test(line));
  if (start < 0) throw new Error(`preset entry ${id} not found`);
  let end = start + 1;
  while (end < lines.length && !/^    - id: /.test(lines[end])) end += 1;
  return lines.slice(start, end).map((line) => (line.startsWith('    ') ? line.slice(4) : line)).join('\n');
}

function replaceEngine(block) {
  const lines = block.split('\n');
  const out = [];
  let replaced = false;
  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index];
    const nameMatch = /^(\s*)name: '@deepseek-ai\/dsh-compaction-basic'\s*$/.exec(line);
    if (!replaced && nameMatch !== null) {
      const indent = nameMatch[1];
      out.push(`${indent}name: '${ENGINE_ROW.name}'`);
      out.push(`${indent}config:`);
      for (const [key, value] of ENGINE_ROW.config) out.push(`${indent}  ${key}: ${value}`);
      replaced = true;
      // Drop the replaced row's previous config block, if it had one. A preset
      // that already owns a configured compaction-basic row (for example the
      // runtime-fixed minimal preset) would otherwise receive a duplicate
      // `config:` key.
      let cursor = index + 1;
      if (cursor < lines.length && lines[cursor] === `${indent}config:`) {
        cursor += 1;
        while (cursor < lines.length && (lines[cursor].startsWith(`${indent}  `) || lines[cursor].trim().length === 0)) cursor += 1;
        index = cursor - 1;
      }
      continue;
    }
    out.push(line);
  }
  if (!replaced) throw new Error('compaction-basic row not found in preset entry');
  return out.join('\n');
}

function replacePruner(block) {
  return block
    .replace(/^(\s*)thresholdChars: 8192\s*$/m, '$1thresholdChars: 16384')
    .replace(/^(\s*)headChars: 4096\s*$/m, '$1headChars: 12288')
    .replace(/^(\s*)tailChars: 1024\s*$/m, '$1tailChars: 2048');
}

/**
 * Some presets (notably `minimal`) do not mount a compaction row at all. Add a
 * complete compaction group so the Compaction-Fidelity engine becomes the preset's backend
 * instead of relying on a row that does not exist.
 */
function insertEngineGroup(block) {
  const indent = '      ';
  const lines = [
    `${indent}- id: compaction`,
    `${indent}  name: cordis:group`,
    `${indent}  group: true`,
    `${indent}  isolate:`,
    `${indent}    compaction: true`,
    `${indent}    toolResultPruner: true`,
    `${indent}  config:`,
    `${indent}    - id: compaction-basic`,
    `${indent}      name: '${ENGINE_ROW.name}'`,
    `${indent}      config:`,
    ...ENGINE_ROW.config.map(([key, value]) => `${indent}        ${key}: ${value}`),
    `${indent}    - id: command-compact`,
    `${indent}      name: '@deepseek-ai/dsh-command-compact'`,
    `${indent}    - id: tool-result-pruner`,
    `${indent}      name: '@deepseek-ai/dsh-compaction-tool-result-pruner'`,
    `${indent}      config:`,
    `${indent}        thresholdChars: 16384`,
    `${indent}        headChars: 12288`,
    `${indent}        tailChars: 2048`,
  ];
  return `${block.trimEnd()}\n${lines.join('\n')}`;
}

/** Replace an existing compaction-basic row, or insert the whole group. */
function ensureCompaction(block) {
  if (block.includes("@deepseek-ai/dsh-compaction-basic")) return replaceEngine(block);
  return insertEngineGroup(block);
}

const blocks = [];
for (const preset of PRESETS) {
  const source = readFileSync(join(APP_NODE_MODULES, preset.file), 'utf8');
  let entry = extractEntry(source, preset.id);
  entry = ensureCompaction(entry);
  entry = replacePruner(entry);
  blocks.push(entry.trimEnd());
}

const header = [
  '# Generated by dsh-compaction-fidelity scripts/generate-preset-patch.mjs',
  `# Target: DSH ${DSH_VERSION} (DeepSeek Harness Desktop app node_modules)`,
  '# This bundle patch:',
  '#   1. inserts the Compaction-Fidelity host plugin row (tools, commands, index, anchor injection);',
  '#   2. overrides the built-in standard/cordis/ptc/minimal agent presets by id,',
  '#      replacing their compaction-basic row (or inserting a compaction group in',
  '#      minimal) with dsh-compaction-fidelity/engine and widening the pruner.',
  '# Remove this bundle to restore the built-in DSH presets. Running sessions keep',
  '# their composed plugin tree until restarted.',
  '',
].join('\n');

const hostRow = [
  '- insert:',
  "    - id: compaction-fidelity",
  "      name: 'dsh-compaction-fidelity'",
  '      config:',
  '        enabled: true',
  '        autoIndex: true',
  '        anchorInjection: true',
  '        indexDir: .dsh/compaction-fidelity',
  '        anchorsPerFile: 8',
  '        maxFiles: 20000',
  '        maxFileBytes: 1048576',
  '        archFilesLimit: 60',
].join('\n');

const output = `${header}${hostRow}\n\n${blocks.join('\n\n')}\n`;
writeFileSync(new URL('../cordis.patch.yml', import.meta.url), output, 'utf8');
console.log(`wrote cordis.patch.yml (${output.split('\n').length} lines)`);
